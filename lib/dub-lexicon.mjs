export function lexiconCoverage(tags) {
  const src = tags || {};
  const miss = { theme: [], emotion: [], scene: [], pace: [] };
  for (const k of Object.keys(miss)) {
    for (const t of src[k] || []) if (!TAG_LEXICON[k][t]) miss[k].push(t);
  }
  return miss;
}
